rng = np.random.default_rng(0)
out = {}

X = np.array([[0, 1], [1, 0]], complex)
Y = np.array([[0, -1j], [1j, 0]])
Z = np.diag([1.0 + 0j, -1])
I2 = np.eye(2)


def op(n, i, P):
    mats = [I2] * n
    mats[i] = P
    r = mats[0]
    for m in mats[1:]:
        r = np.kron(r, m)
    return r


# 1) Full 2^n state-vector simulation with the Heisenberg exchange Hamiltonian
#    H_ab = (X_aX_b + Y_aY_b + Z_aZ_b + I)/2 = SWAP_ab, gate exp(-i theta H_ab).
def full_check(n=6, conn="chain", depth=4):
    circ = ExchangeCircuit(n, make_layers(n, conn, depth)) if conn == "chain" else None
    pairs = circ.pairs()
    theta = rng.normal(size=circ.n_gates)
    U = np.eye(2 ** n, dtype=complex)
    g = 0
    for a, b in pairs:
        for x, y in zip(a, b):
            H = 0.5 * (op(n, x, X) @ op(n, y, X) + op(n, x, Y) @ op(n, y, Y) + op(n, x, Z) @ op(n, y, Z) + np.eye(2 ** n))
            U = sl.expm(-1j * theta[g] * H) @ U
            g += 1
    weight = np.array([bin(i).count("1") for i in range(2 ** n)])
    leak = 0.0
    errs = []
    for k in range(n):
        idx = 1 << (n - 1 - k)  # qubit k excited (big-endian kron order)
        col = U[:, idx]
        leak = max(leak, np.sum(np.abs(col[weight != 1]) ** 2))
        amp_full = np.array([col[1 << (n - 1 - j)] for j in range(n)])
        sub = circ(basis_states(torch.tensor([k]), n, torch.complex128), torch.tensor(theta)[None]).numpy()[0]
        # equal up to a global phase
        ph = np.vdot(sub, amp_full)
        ph /= abs(ph)
        errs.append(np.abs(amp_full - ph * sub).max())
    # SU(2) invariance: [U, S_total^2] = 0
    Sx = sum(op(n, i, X) for i in range(n)) / 2
    Sy = sum(op(n, i, Y) for i in range(n)) / 2
    Sz = sum(op(n, i, Z) for i in range(n)) / 2
    S2 = Sx @ Sx + Sy @ Sy + Sz @ Sz
    return {"n": n, "max_amp_err": float(max(errs)), "max_leakage": float(leak),
            "comm_S2": float(np.abs(U @ S2 - S2 @ U).max())}


out["full_hilbert_space"] = full_check()

# 2) Lie algebra generated by {i L_ab} on the one-hot subspace.
def lie_dim(V, edges, tol=1e-9):
    gens = []
    for a, b in edges:
        L = np.zeros((V, V))
        L[a, a] = L[b, b] = 1
        L[a, b] = L[b, a] = -1
        gens.append(1j * L)
    basis = []

    def add(M):
        v = np.concatenate([M.real.ravel(), M.imag.ravel()])
        if basis:
            B = np.array(basis)
            v = v - B.T @ (B @ v)
        nv = np.linalg.norm(v)
        if nv > tol:
            basis.append(v / nv)
            return True
        return False

    elems = []
    for G in gens:
        if add(G):
            elems.append(G)
    frontier = list(elems)
    while frontier:
        new = []
        for A in frontier:
            for G in gens:
                C = A @ G - G @ A
                if add(C):
                    new.append(C)
        elems += new
        frontier = new
    return len(basis)


lie = {}
for V in [4, 6, 8]:
    chain = [(i, i + 1) for i in range(V - 1)]
    lie[f"chain_V{V}"] = {"dim": lie_dim(V, chain), "u(V-1)": (V - 1) ** 2, "u(V)": V ** 2}
for V in [4, 8]:
    bfly = [(a, b) for A, Bv in make_layers(V, "butterfly", 1) for a, b in zip(A, Bv)]
    lie[f"butterfly_V{V}"] = {"dim": lie_dim(V, bfly), "u(V-1)": (V - 1) ** 2, "u(V)": V ** 2}
out["lie_algebra"] = lie

# 3) W-state invariance and the sum rule sum_k <k|U|x> = 1 (V=32, random deep circuit)
V = 32
circ = ExchangeCircuit(V, make_layers(V, "butterfly", 3))
theta = torch.randn(5, circ.n_gates, dtype=torch.float64) * 2
W = torch.full((5, V), 1 / np.sqrt(V), dtype=torch.complex128)
out["W_invariance_err"] = float((circ(W, theta) - W).abs().max())
cols = circ(basis_states(torch.arange(5), V, torch.complex128), theta)
out["sum_rule_err"] = float((cols.sum(1) - 1).abs().max())

# 4) Two-term parameter-shift rule with shift pi/4 (generator SWAP has eigenvalues +-1)
x, k = 3, 17
th = torch.randn(1, circ.n_gates, dtype=torch.float64)
f = lambda T: (circ(basis_states(torch.tensor([x]), V, torch.complex128), T)[0, k].abs() ** 2).item()
errs = []
for g in rng.choice(circ.n_gates, 10, replace=False):
    Tg = th.clone().requires_grad_()
    p = circ(basis_states(torch.tensor([x]), V, torch.complex128), Tg)[0, k].abs() ** 2
    p.backward()
    e = torch.zeros_like(th)
    e[0, g] = np.pi / 4
    ps = f(th + e) - f(th - e)
    errs.append(abs(ps - Tg.grad[0, g].item()))
out["parameter_shift_max_err"] = float(max(errs))

# 5) Column reachability: fit random target distributions with a single circuit column
def fit(target, x, conn, depth, steps=3000, seed=0):
    torch.manual_seed(seed)
    c = ExchangeCircuit(V, make_layers(V, conn, depth))
    th = (torch.rand(1, c.n_gates, dtype=torch.float64) - 0.5).requires_grad_()
    opt = torch.optim.Adam([th], lr=0.05)
    psi0 = basis_states(torch.tensor([x]), V, torch.complex128)
    for _ in range(steps):
        p = c(psi0, th)[0].abs() ** 2
        kl = (target * (target.clamp_min(1e-30).log() - p.clamp_min(1e-30).log())).sum()
        opt.zero_grad()
        kl.backward()
        opt.step()
    return kl.item()


reach = {}
for conc in [0.1, 1.0]:
    for conn, depth in [("butterfly", 1), ("butterfly", 3), ("chain", 16), ("chain", 32)]:
        kls = []
        for s in range(5):
            tgt = torch.tensor(rng.dirichlet(np.full(V, conc)), dtype=torch.float64)
            kls.append(fit(tgt, int(rng.integers(V)), conn, depth, seed=s))
        reach[f"dir{conc}_{conn}{depth}"] = {"median_kl_nats": float(np.median(kls)), "max_kl_nats": float(max(kls))}
        print(conc, conn, depth, reach[f"dir{conc}_{conn}{depth}"], flush=True)
out["column_reachability"] = reach

